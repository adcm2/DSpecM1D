#!/usr/bin/env python3
"""Build the standalone guide and the repository's strict Doxygen API."""
import argparse
import html
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]

def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', default='build/guide-docs', help='ignored output directory (must be under build/)')
    args = parser.parse_args()
    output = (ROOT / args.output).resolve() if not Path(args.output).is_absolute() else Path(args.output).resolve()
    build_root = (ROOT / 'build').resolve()
    try:
        output.relative_to(build_root)
    except ValueError:
        parser.error('output must be inside this repository\'s build/ directory')
    if output == build_root:
        parser.error('output must be a dedicated subdirectory of build/')
    doxygen = shutil.which('doxygen')
    if not doxygen:
        parser.error('Doxygen 1.9.8 is required; install it and retry')
    version = subprocess.check_output([doxygen, '--version'], text=True).strip()
    if version != '1.9.8':
        parser.error(f'this checked build uses Doxygen 1.9.8; found {version}')

    try:
        revision = subprocess.check_output(['git', 'rev-parse', 'HEAD'], cwd=ROOT, text=True).strip()
        branch = subprocess.check_output(['git', 'branch', '--show-current'], cwd=ROOT, text=True).strip()
    except subprocess.CalledProcessError as error:
        parser.error(f'cannot determine source revision: {error}')
    marker = output / '.yspecpp-docs-build'
    if output.exists():
        if (marker.is_symlink() or not marker.is_file() or
                marker.read_text() != 'Generated by docs/tools/build_docs.py\n'):
            parser.error(f'refusing to replace unmanaged output directory: {output}')
        for owned in (output / 'site', output / 'Doxyfile'):
            if owned.is_symlink():
                parser.error(f'refusing to replace symlink in owned output: {owned}')
            if owned.is_dir(): shutil.rmtree(owned)
            elif owned.exists(): owned.unlink()
    else:
        output.mkdir(parents=True)
    site = output / 'site'
    api = site / 'api'
    if api.exists(): shutil.rmtree(api)
    shutil.copytree(ROOT / 'docs/site', site)
    shutil.copy2(ROOT / 'docs/theory/adjoint-kernels.pdf', site / 'assets/adjoint-kernels.pdf')
    shutil.copy2(ROOT / 'examples/prem.200', site / 'examples/prem.200')
    dirty = bool(subprocess.check_output(['git', 'status', '--porcelain', '--untracked-files=all'], cwd=ROOT, text=True).strip())
    if dirty:
        dirty_notice = (f'Code base revision: <code>{revision}</code>. This preview includes uncommitted working-tree changes '
                        f'on <code>{branch or "detached HEAD"}</code>; the SHA alone does not contain this manual.')
    else:
        dirty_notice = (f'Source revision: <code>{revision}</code>. This manual and API were built from this checkout; '
                        f'use this SHA when reproducing the documentation.')
    nav_template = (site / 'templates/navigation.html').read_text()
    page_template = (site / 'templates/page-shell.html').read_text()
    for template in ('navigation.html', 'page-shell.html'):
        (site / 'templates' / template).unlink()
    (site / 'templates').rmdir()
    manual_pages = sorted(site.glob('*.html'))
    for page in manual_pages:
        source = page.read_text()
        metadata = re.fullmatch(
            r'<!-- title: (.+)\ndescription: (.+) -->\s*(<main class="page">.*</main>)\s*',
            source,
            flags=re.S,
        )
        if not metadata:
            parser.error(f'authored page lacks title/description metadata or main content: {page.name}')
        title, description, content = metadata.groups()
        navigation = nav_template
        for manual_page in manual_pages:
            name = manual_page.name
            navigation = navigation.replace('{{CURRENT:' + name + '}}', 'aria-current="page"' if page.name == name else '')
        rendered = page_template.replace('{{TITLE}}', html.escape(title, quote=True))
        rendered = rendered.replace('{{DESCRIPTION}}', html.escape(description, quote=True))
        rendered = rendered.replace('{{NAVIGATION}}', navigation).replace('{{PAGE_CONTENT}}', content)
        page.write_text(rendered.replace('{{REVISION_NOTICE}}', dirty_notice).replace('{{BASE_REVISION}}', revision))

    cmake = (ROOT / 'CMakeLists.txt').read_text()
    match = re.search(r'project\(YSpec\s+VERSION\s+([^\s)]+)', cmake)
    if not match:
        parser.error('could not derive PROJECT_VERSION from CMakeLists.txt')
    template = (ROOT / 'docs/Doxyfile.in').read_text()
    substitutions = {
        '@PROJECT_VERSION@': match.group(1),
        '@DOXYGEN_OUTPUT_DIR@': str(api),
        '@DOXYGEN_INPUT_DIR@': str(ROOT / 'YSpec'),
        '@PROJECT_SOURCE_DIR@': str(ROOT),
    }
    for key, value in substitutions.items():
        template = template.replace(key, value)
    if re.search(r'@[A-Z][A-Z0-9_]*@', template):
        parser.error('unsubstituted placeholder remains in docs/Doxyfile.in')
    # The source template keeps all upstream warning, input, and extraction settings.
    config = output / 'Doxyfile'
    config.write_text(template + '\nHTML_OUTPUT = .\n')
    api.mkdir(parents=True)
    marker.write_text('Generated by docs/tools/build_docs.py\n')
    run = subprocess.run([doxygen, str(config)], cwd=ROOT, text=True, capture_output=True)
    if run.stdout:
        print(run.stdout, end='')
    if run.stderr:
        print(run.stderr, end='', file=sys.stderr)
    # Doxygen sends its warnings to the log, and may say nothing elsewhere:
    # show the log whenever the build is rejected, so CI states the reason.
    warning_log = api / 'doxygen-warnings.log'
    warnings = warning_log.read_text() if warning_log.exists() else ''
    if run.returncode or warnings:
        if warnings:
            print(f'Doxygen warnings ({warning_log}):', file=sys.stderr)
            print(warnings, end='', file=sys.stderr)
        return run.returncode or 1
    if not (api / 'index.html').is_file():
        print('Doxygen did not create api/index.html', file=sys.stderr)
        return 1
    # README links are relative to the repository root; the generated main page lives in site/api/.
    main_page = api / 'index.html'
    main_page.write_text(main_page.read_text().replace('href="docs/site/', 'href="../'))
    print(f'Built guide and strict API with Doxygen {version} from {revision}')
    print(f'Output: {output}')
    return 0

if __name__ == '__main__':
    raise SystemExit(main())
